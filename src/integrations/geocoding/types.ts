/**
 * Address standardization port (Route Optimizer feature).
 *
 * An employee types a few characters, picks a real address from a list, and
 * the platform stores what the provider returned rather than what was typed.
 * That is the only point in the system where a free-text address becomes a
 * coordinate — everything downstream (routing, navigation, distance) reads
 * the stored pair and never geocodes again.
 *
 * The server brokers every call. The API key stays here: the dashboard has a
 * strict CSP with `connect-src 'self'` and no NEXT_PUBLIC_* convention, and
 * the driver app has no key at all. Defining this as a port keeps the order
 * flow testable without credentials, exactly as the routing port does.
 *
 * SESSION TOKENS
 *
 * Google bills autocomplete per keystroke-request unless the requests are
 * grouped into a session that ends with one details lookup. The token is
 * generated by the caller, passed through every suggest() for one picking
 * session, and passed once more to the resolve() that closes it. Getting this
 * wrong is a billing bug, not a correctness bug, which is exactly why it is
 * in the interface where it cannot be forgotten.
 */

export interface PlaceSuggestion {
  placeId: string;
  /** The line to show in bold — usually street number and name. */
  primaryText: string;
  /** The disambiguating remainder — city, region, country. */
  secondaryText: string;
}

export interface ResolvedPlace {
  placeId: string;
  formattedAddress: string;
  latitude: number;
  longitude: number;
}

export interface SuggestOptions {
  /**
   * Groups a burst of keystrokes and the details lookup that follows into one
   * billable session.
   */
  sessionToken: string;
  /**
   * Bias, not a filter. A pharmacy delivers around itself, so its own
   * coordinate makes the first suggestion the right one far more often. Absent
   * when the organization has not been geocoded yet.
   */
  origin?: { latitude: number; longitude: number };
}

export interface PlacesProvider {
  readonly name: string;

  /**
   * Address suggestions for a partial input. Returns an empty list rather
   * than throwing when the provider has nothing — "no match" is a normal
   * answer while someone is still typing.
   */
  suggest(input: string, options: SuggestOptions): Promise<PlaceSuggestion[]>;

  /**
   * Turns a chosen suggestion into a standardized address and a coordinate.
   *
   * Throws when the place cannot be resolved. Unlike suggest(), this one is
   * called after a deliberate human choice, so silence would strand the
   * employee with a form that will not save and no reason why.
   */
  resolve(placeId: string, sessionToken: string): Promise<ResolvedPlace>;
}
